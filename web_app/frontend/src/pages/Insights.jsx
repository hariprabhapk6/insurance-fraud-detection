import SectionHeading from '../components/SectionHeading.jsx';
import { StatTile, ClassSplit, ConfusionMatrix, BarList } from '../components/Charts.jsx';
import metrics from '../data/metrics.json';

// Every value below is read from src/data/metrics.json, which is exported from the project's saved result files.
const { dataset: ds, ml, nlp, mlp, rnn, gnn, genai, agent } = metrics;
const rf = ml.random_forest.metrics;
const lr = ml.logistic_regression.metrics;
const [[tn, fp], [fn, tp]] = ml.random_forest.confusion_matrix;
const n3 = (x) => x.toFixed(3);

const FEATURE_LABEL = {
  desc_length: 'Description length', desc_word_count: 'Description word count',
  policy_tenure_months: 'Policy tenure (months)', prior_claims_count: 'Prior claims',
  claimant_age: 'Claimant age', annual_income: 'Annual income',
  claim_to_income_ratio: 'Claim-to-income ratio', claim_amount: 'Claim amount',
  claim_month: 'Claim month', claim_dow: 'Claim day of week',
};

const auc = [
  { label: 'Text classifier (NLP)', value: nlp.metrics.roc_auc },
  { label: 'Random Forest (ML)', value: rf.roc_auc, tone: 'accent' },
  { label: 'Graph network (GCN)', value: gnn.metrics.auc },
  { label: 'MLP (deep, tabular)', value: mlp.metrics.roc_auc },
  { label: 'RNN on event sequences', value: rnn.metrics.auc },
  { label: 'Logistic Regression (ML)', value: lr.roc_auc },
].sort((a, b) => b.value - a.value);

export default function Insights() {
  const flagged = tp + fp;
  const frauds = tp + fn;
  const allNegAcc = (tn + fp) / (tn + fp + fn + tp);
  return (
    <>
      <section className="page-head">
        <div className="container">
          <h1>How well does the model work?</h1>
          <p>Verified results from the project&rsquo;s saved evaluation files, with the caveats that matter for reading them.</p>
        </div>
      </section>

      <section className="section">
        <div className="container insight">
          <SectionHeading title="The data" id="data">
            The models learn from {ds.total_claims.toLocaleString()} synthetic claims. Fraud is rare, which shapes every metric below.
          </SectionHeading>
          <div className="card">
            <ClassSplit fraud={ds.fraud} notFraud={ds.not_fraud} />
            <p className="source">
              {ds.train_size.toLocaleString()} claims trained the models and {ds.test_size.toLocaleString()} were held back as a test set
              (stratified 80/20 split). Source: {ds.source}.
            </p>
          </div>
          <div className="notice">
            <p>
              The dataset was generated by code, and its descriptions come from only {ds.distinct_descriptions} distinct texts.
              Fraudulent claims use different wording from genuine ones, so text features are far easier here than in real life.
              Treat the scores as proof the method works, not a forecast for real claims.
            </p>
          </div>
        </div>
      </section>

      <section className="section section-grey">
        <div className="container insight">
          <SectionHeading title="Random Forest on the test set" id="rf">
            These five numbers describe the model behind the Analyze page, measured on {ds.test_size.toLocaleString()} claims it did not train on.
          </SectionHeading>
          <div className="stat-grid">
            <StatTile label="Accuracy" value={n3(rf.accuracy)} note="Share of claims classified correctly" />
            <StatTile label="Precision" value={n3(rf.precision)} note={`${tp} of ${flagged} flagged claims were fraud`} />
            <StatTile label="Recall" value={n3(rf.recall)} note={`${tp} of ${frauds} fraud claims were caught`} />
            <StatTile label="F1-score" value={n3(rf.f1)} note="Balance of precision and recall" />
            <StatTile label="ROC-AUC" value={n3(rf.roc_auc)} note="How well scores rank fraud above genuine" />
          </div>
          <div className="notice notice-warn">
            <p>
              Accuracy looks high because most claims are genuine: labelling every claim &ldquo;not fraud&rdquo; would already be right{' '}
              {(allNegAcc * 100).toFixed(1)}% of the time. Precision, recall and ROC-AUC say more about fraud detection.
            </p>
          </div>
          <p className="source">Source: {ml.source}. These are test-set metrics at the 0.5 decision threshold, not the fraud score of any single claim.</p>
        </div>
      </section>

      <section className="section">
        <div className="container two-col insight">
          <div>
            <h2>What the errors look like</h2>
            <p>
              The model flagged {flagged} claims. {tp} were fraud and {fp} were false alarms that a reviewer would clear.
              It missed {fn} of the {frauds} fraudulent claims.
            </p>
            <p>Whether that trade is acceptable depends on how costly a missed fraud is compared with an unnecessary review.</p>
          </div>
          <div className="card">
            <ConfusionMatrix tn={tn} fp={fp} fn={fn} tp={tp} />
          </div>
        </div>
      </section>

      <section className="section section-grey">
        <div className="container two-col insight">
          <div>
            <h2>What the model relies on</h2>
            <p>
              Importance is how much each input helped the forest split claims. It describes the model overall, not the reason behind any one result.
            </p>
            <div className="notice notice-warn">
              <p>
                The two most important features are the description&rsquo;s length and word count. In this synthetic data, fraud
                descriptions are phrased differently from genuine ones, so length works as a shortcut. A real dataset would likely rank features differently.
              </p>
            </div>
          </div>
          <div className="card">
            <BarList
              items={ml.top_features.map(([name, v]) => ({
                label: FEATURE_LABEL[name] || name, value: v, display: `${(v * 100).toFixed(1)}%`,
              }))}
            />
            <p className="source">Top 10 of the Random Forest&rsquo;s feature importances. Source: {ml.source}.</p>
          </div>
        </div>
      </section>

      <section className="section">
        <div className="container insight">
          <SectionHeading title="Models across the project" id="compare">
            ROC-AUC for each approach the project tried. Higher is better, and 0.5 is no better than guessing.
          </SectionHeading>
          <div className="card">
            <BarList items={auc.map((a) => ({ ...a, display: n3(a.value) }))} max={1} />
            <p className="source">
              Not a fair race: the models solve different tasks on different test sets. The GCN scored {gnn.test_nodes} policyholders,
              and the RNN flagged no claims at its 0.5 threshold (precision and recall 0) despite an AUC of {n3(rnn.metrics.auc)}.
              Sources: 01_ml, 02_dl, 03_nlp result files.
            </p>
          </div>
        </div>
      </section>

      <section className="section section-grey">
        <div className="container insight">
          <SectionHeading title="Stress tests and the agent" id="extras">
            Two experiments that probe how the detector behaves beyond the standard test set.
          </SectionHeading>
          <div className="two-col">
            <div className="card">
              <h3>Synthetic fraud stress test</h3>
              <p>
                The Random Forest flagged only <strong>{(genai.stress_detection_rate * 100).toFixed(1)}%</strong> of {genai.n_synthetic} newly
                generated fraud claims, a sign it relies on the exact patterns it was trained on.
              </p>
              <p>
                Retraining with that synthetic fraud added raised ROC-AUC from <strong>{n3(genai.baseline.roc_auc)}</strong> to{' '}
                <strong>{n3(genai.augmented.roc_auc)}</strong> and recall from {n3(genai.baseline.recall)} to {n3(genai.augmented.recall)},
                while precision fell from {n3(genai.baseline.precision)} to {n3(genai.augmented.precision)}.
              </p>
              <p className="source">Source: {genai.source}. Test set unchanged and real-only.</p>
            </div>
            <div className="card">
              <h3>Investigation agent (simulation)</h3>
              <p>
                In a simulation of {agent.total_decisions.toLocaleString()} claims, the agent sent <strong>{(agent.fraud_caught_rate * 100).toFixed(1)}%</strong> of
                fraud cases to a human reviewer and auto-approved {agent.auto_approved_count.toLocaleString()}.
              </p>
              <p className="source">
                Caution: claims were sampled from the full dataset, including ones the models trained on, so this is likely optimistic. Source: {agent.source}.
              </p>
            </div>
          </div>
        </div>
      </section>
    </>
  );
}
